/** 四轴轮转顺序 —— 保证 20 题均衡覆盖 */
export const AXIS_CYCLE = ['EI', 'NS', 'TF', 'JP']

/**
 * 取出某一轴的母题原型。
 * @param axis 四轴之一
 * @param index 该轴内的题序（用于轮转取用）
 */
export function getPrototypes(axis, index = 0) {
  const list = AXIS_CANON[axis]?.prototypes ?? AXIS_CANON.EI.prototypes
  const n = list.length
  return list[((index % n) + n) % n]
}

/**
 * 取出该轴的全部母题原型（供本地兜底题库构建）。
 */
export function getPrototypeList(axis) {
  return AXIS_CANON[axis]?.prototypes ?? []
}
