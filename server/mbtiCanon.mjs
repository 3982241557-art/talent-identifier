/**
 * MBTI 官方维度题库母本（v7.0 · 任务 2）
 *
 * 【为什么需要这个】
 * v6.0 的做法是把「轴 + 历史回答」丢给模型，让它自由发挥出题。
 * 结果是：题目质量完全取决于模型当天的状态 ——
 * 偶尔出的是「你更喜欢独处还是社交」这种毫无区分度的废话，
 * 偶尔又出的是跟 MBTI 毫无关系的脑筋急转弯。
 *
 * 【v7.0 的做法】
 * 把 MBTI 官方测评（Form M / Form Q）的**经典维度原型题**固化成母题库，
 * 模型只允许在母题基础上做「情境变体 + 顺序重排」，
 * 绝不允许自由发挥题目内核。这样：
 *   · 题目永远指向真实的维度行为
 *   · AI 的价值转移到「结合用户历史回答的个性化改写」上
 *   · 即使 AI 挂掉，本地兜底题库也同样源自母题本，规格一致
 */

