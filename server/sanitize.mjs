/* ============================================================
 *  主函数
 * ============================================================ */

/**
 * 清洗 AI 返回的文本。
 *
 * @param text     原始文本
 * @param options
 *   · jargon  是否替换专业术语（默认 true）
 *   · tells   是否清理 AI 腔（默认 true）
 *   · banned  是否改写禁用句式（默认 true）
 *   · max     是否截断到指定字数
 */
export function sanitize(text, options = {}) {
  const { jargon = true, tells = true, banned = true, max } = options
  if (typeof text !== 'string' || !text) return ''

  let t = text

  /* ---- 1. 禁用句式（先做，因为它们最显眼） ---- */
  if (banned) {
    for (const [re, rep] of BANNED_PATTERNS) {
      t = t.replace(re, rep)
    }
  }

  /* ---- 2. 专业术语 ---- */
  if (jargon) {
    for (const [re, rep] of JARGON_WORDS) {
      t = t.replace(re, rep)
    }
    /* 替换后可能出现重复尾巴 */
    t = t.replace(/(你的天性)+/g, '你的天性')
    t = t.replace(/(人生领域)+/g, '人生领域')
    t = t.replace(/(这股力量)+/g, '这股力量')
    t = t.replace(/(你的人生课题)+/g, '你的人生课题')
  }

  /* ---- 3. AI 腔 ---- */
  if (tells) {
    for (const [re, rep] of AI_TELLS) {
      t = t.replace(re, rep)
    }
  }

  /* ---- 3.5 清理替换后可能出现的重复词尾 ---- */
  t = t.replace(/说白了就是是/g, '说白了就是')
  t = t.replace(/其实是是/g, '其实是')
  t = t.replace(/真正要紧的是是/g, '真正要紧的是')

  /* ---- 4. 标点整理 ---- */
  t = t.replace(/[，,]{2,}/g, '，')
  t = t.replace(/[。]{2,}/g, '。')
  t = t.replace(/[，,]\s*[。]/g, '。')
  t = t.replace(/[。]\s*[，,]/g, '。')
  t = t.replace(/；\s*。/g, '。')
  t = t.replace(/^[，,、；;\s]+/, '')
  t = t.replace(/[ \t]{2,}/g, ' ')

  /* ---- 5. 截断 ---- */
  if (max && t.length > max) {
    const slice = t.slice(0, max)
    const cut = Math.max(
      slice.lastIndexOf('。'),
      slice.lastIndexOf('，'),
      slice.lastIndexOf('；'),
      slice.lastIndexOf('、'),
    )
    t =
      cut >= max * 0.5
        ? `${slice.slice(0, cut).replace(/[，,、；;]$/, '')}。`
        : `${slice.replace(/[，,、；;]$/, '')}。`
  }

  return t.trim()
}

/**
 * 判断文本里是否还残留禁用句式。
 * 用于自动化校验。
 */
export function hasBannedPattern(text) {
  if (typeof text !== 'string' || !text) return false
  return BANNED_PATTERNS.some(([re]) => {
    const r = new RegExp(re.source, re.flags.replace('g', ''))
    return r.test(text)
  })
}

/**
 * 判断文本里是否残留专业术语。
 */
export function hasJargon(text) {
  if (typeof text !== 'string' || !text) return false
  return JARGON_WORDS.some(([re]) => {
    const r = new RegExp(re.source, re.flags.replace('g', ''))
    return r.test(text)
  })
}

