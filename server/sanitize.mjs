/* ============================================================
 *  四、今日运势专用 —— 「只讲今天」强制清洗
 * ============================================================
 *
 *  【为什么要单独一层】
 *  通用净化器只管句式和术语，管不住**时间尺度**。
 *
 *  实际踩过的坑：
 *    Prompt 里已经明令「绝对不许出现未来几天」，
 *    模型偶尔还是会写「接下来一周手头的事会慢慢顺起来」。
 *
 *  这类句子单看每一句都通顺，放进「今日运势」就串味了 ——
 *  用户点开「今日运势」，读到的却是一周的节奏。
 *
 *  【解法】
 *  代码层直接把长周期表述改写成今天的口径。
 *  宁可句子糙一点，也不能让时间尺度跑偏。
 */

/** 长周期表述 → 今天口径 */
const DAILY_SCOPE_REWRITES = [
  /* 「接下来一周 / 这周 / 本周」 */
  [
    /接下来(?:的)?(?:一)?(?:周|星期)(?:里|内|中)?/g,
    '接下来这几天',
  ],
  [/(?:这|本)(?:一)?(?:周|星期)(?:里|内|中)?/g, '今天'],
  [/(?:未来|接下来)(?:的)?(?:几|三|五|七|十)(?:天|日|周|个?月)/g, '今天'],
  /* 「这个月 / 本月 / 下个月」 */
  [/(?:这个|本|下个|下)(?:月|月份)/g, '今天'],
  /* 「今年 / 本年度 / 年度」 */
  [/(?:今年|本年度|年度|这一年)/g, '今天'],
  /* 「这个季度 / 季度末」 */
  [/(?:这个|本|下个)(?:季度|季度末|季度初)/g, '今天'],
  /* 「未来 N 天 / N 个月内」 */
  [/(?:未来|接下来)(?:的)?\d+\s*(?:天|日|周|个月|年)(?:里|内|中)?/g, '今天'],
  /* 「上半年 / 下半年 / 月初 / 月末 / 上半月 / 下半月」 */
  [/(?:上|下)半(?:年|月)/g, '今天'],
  [/月初|月末/g, '今天'],
]

/**
 * 把文本里的长周期表述收回到「今天」。
 *
 * @param text 原始文本
 */
export function scrubToToday(text) {
  if (typeof text !== 'string' || !text) return ''
  let t = text
  for (const [re, rep] of DAILY_SCOPE_REWRITES) {
    t = t.replace(re, rep)
  }
  /* 「今天今天」这类替换后的重复要收一收 */
  t = t.replace(/今天今天/g, '今天')
  t = t.replace(/今天之内今天/g, '今天之内')
  t = t.replace(/今天内今天/g, '今天内')
  return t.trim()
}
