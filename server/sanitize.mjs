/* ============================================================
 *  文案净化器 · 服务器版（v16.0）
 * ============================================================
 *
 *  为什么要单独一个文件？
 *  AI 模型的输出不受 100% 控制 —— 即使 Prompt 里写了禁令，
 *  它偶尔还是会蹦出「不是……而是……」这类句式。
 *  所以规则必须落在**代码**里，不能只靠 Prompt 祈祷。
 *
 *  【两道防线】
 *    1. Prompt 层（server/prompt.mjs）—— 把禁令写成最高优先级红线
 *    2. 代码层（本文件）—— 返回给前端前做正则清洗，兜住漏网的
 *
 *  本文件同时被前端复用（server/ 目录在 Workers 里是静态 import，
 *  前端也能从 src/ 引它 —— 见 src/lib/copy.ts 的 re-export）。
 * ============================================================ */

/* ============================================================
 *  一、禁用句式 —— 「不是……而是……」类
 * ============================================================ */

/**
 *  每一项是一个 [正则, 替换模板]。
 *
 *  替换模板里用 $1 / $2 引用捕获组。
 *
 *  为什么要替换而不是直接删？
 *  「你不是冷漠，而是慢热」—— 删掉前半句会变成「，而是慢热」，
 *  句子就断了。替换成「其实你是慢热」才是人话。
 */
const BANNED_PATTERNS = [
  /* ---- 「不是 A，而是 B」 ---- */
  [/不是([^，。！？；、\n]{1,30})[，,]\s*而是([^，。！？；、\n]{1,30})/g, '其实是$2'],
  [/并非([^，。！？；、\n]{1,30})[，,]\s*而是([^，。！？；、\n]{1,30})/g, '其实是$2'],
  [/并不是([^，。！？；、\n]{1,30})[，,]\s*而是([^，。！？；、\n]{1,30})/g, '其实是$2'],

  /* ---- 「不是 A。是 B」 ---- */
  [/不是([^，。！？；、\n]{1,30})[。.]\s*是([^，。！？；、\n]{1,30})/g, '其实是$2'],

  /* ---- 「不在于 A，而在于 B」 ---- */
  [/不在于([^，。！？；、\n]{1,30})[，,]\s*而在于([^，。！？；、\n]{1,30})/g, '真正要紧的是$2'],
  [/并不在于([^，。！？；、\n]{1,30})[，,]\s*而在于([^，。！？；、\n]{1,30})/g, '真正要紧的是$2'],

  /* ---- 「与其说 A，不如说 B」 ---- */
  [/与其说([^，。！？；、\n]{1,30})[，,]\s*不如说([^，。！？；、\n]{1,30})/g, '说白了就是$2'],
  [/与其([^，。！？；、\n]{1,30})[，,]\s*不如([^，。！？；、\n]{1,30})/g, '说白了就是$2'],

  /* ---- 「不只是 A，更是 B」---- */
  [/不只是([^，。！？；、\n]{1,30})[，,]\s*更是([^，。！？；、\n]{1,30})/g, '$1，$2'],

  /* ---- 单独的「而是」引导的对比句 ---- */
  [/而是([^，。！？；、\n]{1,30})/g, '其实是$1'],
]

