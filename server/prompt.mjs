/* ============================================================
 *  v5.0 · 灵魂底色单句 —— 服务端强校验
 *
 *  即便模型偶尔不听话，也必须在这里把它压回「一句话 / 50-80 字」。
 * ============================================================ */

/** 句末终止符 */
const TERMINALS = /[。！？!?…]+/g

/* ============================================================
 *  v7.0 · 第三人称 → 第二人称 强制转换
 *
 *  【为什么需要服务端兜底】
 *  就算 System Prompt 写死「全程用你」，
 *  模型仍然会时不时滑回第三人称（尤其是在描述出生地 + 类型时）。
 *  与占星术语一样，这一层也必须由服务端做最后一道防线。
 * ============================================================ */

/** 第三人称标记 —— 命中即判定为视角错误 */
const THIRD_PERSON_PATTERNS = [
  /他(?![人己])/g, // 他 / 他们 / 他的
  /她/g,
  /其(?!实)/g,
  /此人/g,
  /这位旅人/g,
  /这个人/g,
  /一位旅人/g,
  /这位/g,
]

/**
 * 把第三人称改写成第二人称「你」。
 * 返回改写后的文本；若原本就是第二人称，原样返回。
 */
export function toSecondPerson(text) {
  if (typeof text !== 'string') return ''
  let t = text
  // 先处理更长的、歧义更少的短语
  t = t.replace(/这位旅人/g, '你')
  t = t.replace(/一位旅人/g, '你')
  t = t.replace(/这个人/g, '你')
  t = t.replace(/此人/g, '你')
  t = t.replace(/他们的/g, '你的')
  t = t.replace(/他们/g, '你')
  t = t.replace(/他的/g, '你的')
  t = t.replace(/她的/g, '你的')
  t = t.replace(/她们/g, '你')
  t = t.replace(/他(?![人己])/g, '你')
  t = t.replace(/她/g, '你')
  // 「其」→「你」需要小心，避免破坏「其实」「其他」
  t = t.replace(/其他/g, '另外')
  t = t.replace(/其实/g, '本来')
  t = t.replace(/其(?![实他])/g, '你')
  // 修掉替换后可能出现的重复主语
  t = t.replace(/你出生在(.{2,12})的你/g, '你出生在$1')
  t = t.replace(/([，、。；])\s*你\s*[，、。；]/g, '$1')
  t = t.replace(/的的/g, '的')
  return t.trim()
}

/** 判断文本里是否还残留第三人称 */
export function hasThirdPerson(text) {
  if (typeof text !== 'string') return false
  return THIRD_PERSON_PATTERNS.some((re) => {
    re.lastIndex = 0
    return re.test(text)
  })
}

/**
 * 把模型输出压成合规的单句：
 *  1. 去掉 markdown 围栏、空白与换行
 *  2. 只取第一句（以句号 / 问号 / 叹号 / 省略号切分）
 *  3. 去掉句内多余的句号（只保留结尾一个「。」）
 *  4. 长度夹在 [50, 80] 汉字之间
 *  5. 【v7.0】强制第二人称
 *
 * @returns 压好的单句；若模型输出过短（不足 50 字且无法合并补救），
 *          原样返回第一句，由调用方决定是否采用。
 */
export function normalizeSoulPortrait(raw) {
  if (typeof raw !== 'string') return ''

  let text = raw
    .replace(/```[\s\S]*?```/g, '')
    .replace(/^[\s"'「『【(（]+/, '')
    .replace(/[\s"'」』】)）]+$/, '')
    .replace(/[\r\n]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

  if (!text) return ''

  // 按句末终止符切分，保留每一句
  const sentences = text
    .split(/(?<=[。！？!?…])/)
    .map((s) => s.trim())
    .filter(Boolean)

  if (!sentences.length) return ''

  const MIN = 50
  const MAX = 80

  // 逐句合并，直到长度达标或句子用尽
  let picked = ''
  for (const s of sentences) {
    picked = picked ? `${picked}${s}` : s
    if (picked.length >= MIN) break
  }

  // 去掉句内所有终止符，改为逗号（保留可读的停顿），句末统一为一个「。」
  let body = picked.replace(TERMINALS, '，')
  body = body.replace(/\s+/g, ' ').trim()
  body = body.replace(/[，,]\s*[，,]+/g, '，')
  body = body.replace(/^[，、；,]+/, '').replace(/[，、；,]+$/, '')
  body = body.trim()

  if (!body) return ''

  // 超长：在 [MIN, MAX] 区间内找一个标点断点
  if (body.length > MAX) {
    const slice = body.slice(0, MAX)
    const cut = Math.max(
      slice.lastIndexOf('，'),
      slice.lastIndexOf('、'),
      slice.lastIndexOf('；'),
    )
    body = cut >= MIN ? slice.slice(0, cut).replace(/[，、；,]+$/, '') : slice
  }

  // v7.0：强制第二人称
  body = toSecondPerson(body)

  return `${body}。`
}

