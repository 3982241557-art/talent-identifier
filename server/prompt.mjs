const ASTRO_TERMS = [
  '星座', '白羊', '金牛', '双子', '巨蟹', '狮子', '处女', '天秤', '天蝎',
  '射手', '摩羯', '水瓶', '双鱼', '宫位', '宫', '行星', '本命盘', '星盘',
  '占星', '命理', '相位', '黄道', '天顶', '上升点', '落座', '宫头',
]

/** 判断一句话里是否含占星术语 */
export function hasAstroTerms(text) {
  if (typeof text !== 'string') return false
  return ASTRO_TERMS.some((t) => text.includes(t))
}

/**
 * 去掉占星术语（把命中的词替换成中性表达）。
 * 若替换后句子被破坏得太厉害，则返回空字符串，由调用方使用本地兜底。
 */
export function stripAstroTerms(text) {
  if (typeof text !== 'string') return ''
  let t = text
  // 星座名 → 去掉整个「XX座」表达
  t = t.replace(/[白金双巨狮处天射摩水][羊牛子女蟹子女秤蝎箭瓶鱼]座/g, '')
  t = t.replace(/上升[点]?/g, '')
  t = t.replace(/太阳|月亮|行星|宫位|宫头|相位|黄道|天顶|本命盘|星盘|占星|命理|星座/g, '')
  t = t.replace(/[，,]\s*[，,]+/g, '，')
  t = t.replace(/^[，、；,。]+/, '')
  t = t.replace(/[，、；,]{2,}/g, '，')
  return t.trim()
}

