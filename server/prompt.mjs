/**
 * 把前端传来的星盘压缩为紧凑的上下文描述
 */
export function describeChart(chart) {
  if (!chart || typeof chart !== 'object') return ''
  const bt = chart.bigThree ?? {}
  const fmt = (p) =>
    p ? `${p.sign?.cn ?? '?'}（${p.sign?.element ?? '?'}）` : '?'
  const planets = Array.isArray(chart.planets)
    ? chart.planets
        .map((p) => `${p.planetCn}在${p.sign?.cn ?? '?'}第${p.house ?? '?'}宫`)
        .join('、')
    : ''
  const elements = chart.elements
    ? Object.entries(chart.elements)
        .map(([k, v]) => `${k}:${v}%`)
        .join(' ')
    : ''

  return [
    '【用户星盘】',
    `太阳：${fmt(bt.sun)}　月亮：${fmt(bt.moon)}　上升：${fmt(bt.rising)}`,
    planets ? `行星落座：${planets}` : '',
    elements ? `元素能量占比：${elements}` : '',
    chart.verdict?.text ? `专属判词：${chart.verdict.text}` : '',
  ]
    .filter(Boolean)
    .join('\n')
}

