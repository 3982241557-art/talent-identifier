/**
 * 拼接聊天历史（History Context）
 * 保留最近 N 轮，保证 AI 记得「刚才说过的话」。
 */
export function buildHistory(history, limit = 12) {
  if (!Array.isArray(history)) return []
  return history
    .slice(-limit)
    .filter(
      (h) =>
        h &&
        (h.role === 'user' || h.role === 'assistant') &&
        typeof h.content === 'string' &&
        h.content.trim(),
    )
    .map((h) => ({ role: h.role, content: h.content }))
}

