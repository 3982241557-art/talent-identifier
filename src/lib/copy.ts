/**
 * 判断一段文字里是否含占星术语。
 */
export function hasAstroJargon(text: string): boolean {
  if (typeof text !== 'string' || !text) return false
  const JARGON_WORDS = [
    '宫', '本命', '星盘', '占星', '命理', '相位', '黄道', '天顶',
    '上升', '落座', '行经', '逆行', '顺行',
    '太阳', '月亮', '金星', '木星', '土星', '火星', '水星',
    '海王星', '天王星', '冥王星', '北交点', '南交点',
    '白羊', '金牛', '双子', '巨蟹',
    '狮子', '处女', '天秤', '天蝎', '射手', '摩羯', '水瓶', '双鱼',
  ]
  return JARGON_WORDS.some((w) => text.includes(w))
}

/**
 * 把占星术语换成用户能懂的话。
 *
 * 注意：这是**保守替换** —— 只换词，不动句意。
 * 真正的「温和降维」靠手写文案 + Prompt 约束。
 */
export function stripAstroJargon(text: string): string {
  if (typeof text !== 'string' || !text) return ''
  let t = text
  for (const [re, rep] of JARGON_REPLACEMENTS) {
    t = t.replace(re, rep)
  }
  /* 替换后可能留下重复的「你的天性的」这类尾巴 */
  t = t.replace(/(你的天性的)+/g, '你的天性')
  t = t.replace(/(人生领域)+/g, '人生领域')
  t = t.replace(/(这股力量)+/g, '这股力量')
  t = t.replace(/(你的内在的那股力量)+/g, '你内在的那股力量')
  /* 去掉替换后多余的空格 */
  t = t.replace(/[ \t]{2,}/g, ' ')
  return t.trim()
}

/**
 * v11.0 · 运势文案的统一出口。
 *
 * 流程：去 AI 腔 → 去占星术语 → 温和降维 → 截断。
 *
 * 顺序很关键：**先去术语再截断**，
 * 否则可能把「太阳落在白羊座」截成「太阳落在白」，留下半个词。
 */
export function deAstro(
  text: string,
  options: { max?: number } = {},
): string {
  if (typeof text !== 'string' || !text) return ''
  let t = stripAstroJargon(text)
  t = soften(t)
  if (options.max) t = trimTo(t, options.max)
  return t
}
