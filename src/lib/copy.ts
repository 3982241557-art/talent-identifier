/* ============================================================
 *  文案去 AI 化工具（v9.0 · 任务 4）
 *
 *  ------------------------------------------------------------
 *  目标：把「AI 生成腔」洗掉。
 *
 *  AI 文案的三大特征：
 *    1. **连接词堆砌** —— 「首先…其次…最后…总之…」
 *    2. **说教与总结** —— 「总的来说」「值得注意的是」「需要强调的是」
 *    3. **书面公事腔** —— 「进行」「予以」「具有」「方面」
 *
 *  修复策略：
 *    · 直接**改写文案本身**（本文件之外逐处重写，这是主力）
 *    · 再用 humanize() 做一遍兜底清洗，
 *      专门对付 AI 服务端返回的文本（运势 / 天赋 / 灵魂底色）
 *      —— 那些内容不在本地，不能逐条手改。
 * ============================================================ */

