/**
 * v11.0 · 塔罗解析 —— 极简版。
 *
 * 旧版是三段式（牌面本质 / 今日指引 / 星盘连结），
 * 翻一次牌要读 300+ 字 —— 用户根本读不完，
 * 于是干脆跳过，整个模块就白做了。
 *
 * v11.0 只留两件事：
 *   · 一句「这张牌在说什么」
 *   · 一句「今天做这一件事就好」
 *
 * 全长控制在 60 字以内。
 */
export interface TarotReading {
  /** 一句话点题 */
  gist: string
  /** 今日微小行动指南 */
  action: string
  /** 是否使用了本地兜底 */
  degraded?: boolean
  /* ---------------- v16.0 · 双版本 ---------------- */
  /** ⚡️ 极简版 */
  minimal?: { gist: string; action: string }
  /** 🔭 深度版 */
  deep?: { gist: string; action: string }
}

/**
 * ============================================================
 *  v11.0 · 塔罗极简解析（本地兜底）
 * ============================================================
 *
 *  目标：翻牌后只出现**一两句话**，
 *  并且必须是一个「今天就能做的微小动作」。
 *
 *  【动态防重 · Dynamic Seed】
 *  同一个用户连续两天抽到同一张牌 —— 这在 22 张牌的牌库里
 *  必然会反复发生。如果提示语是牌面自带的固定文案，
 *  用户第二次抽到同一张牌会觉得「又是这句」，神秘感立刻崩塌。
 *
 *  现在用**四路种子**决定提示语：
 *   ① 日期时间戳（今天是哪一天、什么时刻）
 *   ② 星盘变量（太阳/月亮/上升的黄经、元素占比）
 *   ③ 用户的性格底色（MBTI）
 *   ④ 牌本身
 *
 *  四路种子混合后选出一条**当天专属**的行动建议。
 *  同牌不同天 → 不同建议；同牌同天 → 建议稳定（可复现）。
 * ============================================================
 */

