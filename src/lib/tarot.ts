/**
 * 计算 v11.0 的动态种子。
 *
 * 四路输入：时间戳 / 星盘 / 性格 / 牌。
 */
export function readingSeed(
  card: TarotCard,
  chart: Chart | null,
  mbti: MbtiProfile | null,
  timestamp: number,
): number {
  const sun = chart?.bigThree?.sun?.longitude ?? 0
  const moon = chart?.bigThree?.moon?.longitude ?? 0
  const rising = chart?.bigThree?.rising?.longitude ?? 0
  const el = chart?.elements
    ? Object.values(chart.elements).join(',')
    : ''
  const type = mbti?.type ?? 'NONE'

  const timeKey = new Date(timestamp).toISOString().slice(0, 13) // 到小时
  return hash(
    `${card.id}|${timeKey}|${sun.toFixed(1)}|${moon.toFixed(1)}|${rising.toFixed(1)}|${el}|${type}`,
  )
}

/**
 * 本地兜底的极简解析。
 *
 * 保证：即使云端完全不可用，用户也能拿到
 * 一句点题 + 一个今天就能做的微小动作。
 */
export function buildLocalReading(
  card: TarotCard,
  chart: Chart | null,
  mbti: MbtiProfile | null,
  timestamp: number = Date.now(),
): TarotReading {
  const seed = readingSeed(card, chart, mbti, timestamp)
  const pool = CARD_ACTIONS[card.name] ?? GENERIC_ACTIONS
  const action = pool[seed % pool.length]

  /* 点题：直接用牌面自带的 meaning（本身就是一句话） */
  const gist = card.meaning

  return { gist, action }
}
