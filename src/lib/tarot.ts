/* ============================================================
 *  抽牌记录（localStorage）
 * ============================================================ */

const TAROT_KEY = 'talent-identifier:tarot'

export interface TarotRecord {
  /** YYYY-MM-DD */
  date: string
  /** 抽到的牌 id */
  cardId: string
  /** 抽牌时间戳 */
  ts: number
}

/** 读取今天的抽牌记录（没有则返回 null） */
export function readTodayTarot(date: string): TarotRecord | null {
  try {
    const raw = localStorage.getItem(TAROT_KEY)
    if (!raw) return null
    const parsed = JSON.parse(raw) as TarotRecord
    if (!parsed || parsed.date !== date) return null
    return parsed
  } catch {
    return null
  }
}

/** 写入今天的抽牌记录 */
export function writeTodayTarot(date: string, cardId: string): TarotRecord {
  const rec: TarotRecord = { date, cardId, ts: Date.now() }
  try {
    localStorage.setItem(TAROT_KEY, JSON.stringify(rec))
  } catch {
    /* 隐私模式：静默降级，本次会话内仍可用 */
  }
  return rec
}

/* ============================================================
 *  星盘 → 牌面推算
 * ============================================================ */

/** 把任意字符串折成一个 32 位正整数 */
function hash(s: string): number {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

/**
 * 依据星盘 + MBTI + 日期，推算出今天该抽到哪张牌。
 */
export function pickTarotCard(
  chart: Chart | null,
  mbti: MbtiProfile | null,
  date: string,
): TarotCard {
  const sun = chart?.bigThree?.sun?.longitude ?? 0
  const moon = chart?.bigThree?.moon?.longitude ?? 0
  const rising = chart?.bigThree?.rising?.longitude ?? 0
  const elements = chart?.elements
    ? Object.values(chart.elements).join(',')
    : ''
  const type = mbti?.type ?? 'NONE'

  /* ---- 主种子：完全由星盘决定，决定「基准牌」 ---- */
  const seed = hash(`${sun.toFixed(2)}|${moon.toFixed(2)}|${rising.toFixed(2)}|${elements}|${type}`)
  const base = seed % TAROT_DECK.length

  /* ---- 日轮转：在基准牌附近 ±3 张内缓慢移动 ---- */
  const dayHash = hash(date) % 7 // 0~6
  const offset = (dayHash - 3) % TAROT_DECK.length
  const idx = (base + offset + TAROT_DECK.length) % TAROT_DECK.length

  return TAROT_DECK[idx]
}

/**
 * 生成当日「额外提示」—— 一句基于星盘客观数据的说明。
 */
export function tarotChartNote(chart: Chart | null): string {
  if (!chart) return ''
  const el = chart.elements
  const entries = Object.entries(el ?? {}) as Array<[string, number]>
  if (!entries.length) return ''
  const top = entries.sort((a, b) => b[1] - a[1])[0]
  const cn: Record<string, string> = {
    fire: '火象',
    earth: '土象',
    air: '风象',
    water: '水象',
  }
  if (!top || top[1] <= 0) return ''
  return `本命盘里 ${cn[top[0]] ?? top[0]}能量占比 ${Math.round(top[1])}%，是这张盘最显眼的一条主线。`
}

