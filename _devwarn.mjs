import { chromium } from 'playwright-core';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:900}});
const msgs=[];
page.on('console',m=>{const t=m.text(); if(/unique "key"/.test(t)) msgs.push(t);});
page.on('pageerror',e=>msgs.push('PAGEERR '+e.message));
await page.goto('http://127.0.0.1:5180/',{waitUntil:'load'});
await page.waitForTimeout(4000);
for(let i=0;i<6;i++){await page.mouse.click(720,450);await page.waitForTimeout(1800);
  if((await page.evaluate(()=>document.body.innerText)).includes('开始'))break;}
await page.click('button:has-text("开始")');await page.waitForTimeout(1500);
await page.waitForSelector('input[type="date"]');
await page.fill('input[type="date"]','1995-06-15');await page.waitForTimeout(1500);
let sels=await page.$$('select'); if(sels[0]) await sels[0].selectOption({index:1}); await page.waitForTimeout(700);
sels=await page.$$('select'); if(sels[1]) await sels[1].selectOption({index:1}); await page.waitForTimeout(300);
const gb=await page.$('button:has-text("男")'); if(gb) await gb.click();
await page.click('button:has-text("下一步")');await page.waitForTimeout(2500);
await page.click('button:has-text("走进这片星空")').catch(()=>{});await page.waitForTimeout(2500);
await page.click('button:has-text("选择类型")').catch(()=>{});await page.waitForTimeout(1500);
await page.waitForFunction(()=>!!document.querySelector('select option[value="INTJ"]'),{timeout:25000});
await page.selectOption('select','INTJ');await page.waitForTimeout(600);
await page.click('button:has-text("就用它")').catch(()=>{});await page.waitForTimeout(3500);
await page.click('button:has-text("看看我的星盘")').catch(()=>{});await page.waitForTimeout(6000);
const st=await page.evaluate(()=>({astro:!!document.querySelector('svg circle'), body:document.body.innerText.replace(/\s+/g,' ').slice(0,120)}));
console.log('STATE',JSON.stringify(st));
console.log('MSGS',JSON.stringify(msgs,null,1));
await browser.close();
